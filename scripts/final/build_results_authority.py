#!/usr/bin/env python3
"""Build the single results authority under ``outputs/final/``.

Every headline number in the manuscript must trace to one row of one table
in ``outputs/final/`` (protocol v1).  This script consumes ONLY persisted
artifacts:

* ``outputs/conventional/predictions_2021_2023.parquet`` (per-key ensemble
  predictions, regenerated by the holdout scorer)
* ``outputs/conventional/air2stream_2021_2023.parquet`` (unofficial empirical
  comparator, merged onto the same common keys)
* ``data_usgs/panel_usgs_120v2.parquet`` + ``outputs/conventional/panel_2021_2023.parquet``
  (raw observed flags for the key-registry missingness metrics)
* ``data_usgs/station_registry_v1.csv`` (huc2 for the cluster inference)

No torch, no bundles, no network.  The script fails loudly when any
consistency assertion breaks.

Usage::

    python scripts/final/build_results_authority.py
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from thermoroute import conventional_stats as CS  # noqa: E402
from thermoroute import final_results as FR  # noqa: E402

FINAL = ROOT / "outputs" / "final"


def load_registry(path: Path) -> pd.DataFrame:
    registry = pd.read_csv(path, dtype={"site_no": str})
    registry = registry[["site_no", "lat", "lon", "huc2", "drain_area_va"]].copy()
    registry["site_no"] = registry["site_no"].str.strip()
    return registry


def load_combined_panel(dev: Path, holdout: Path) -> pd.DataFrame:
    dev_panel = pd.read_parquet(dev)
    hold_panel = pd.read_parquet(holdout)
    dev_panel["site_id"] = dev_panel["site_id"].astype(str).str.zfill(8)
    hold_panel["site_id"] = hold_panel["site_id"].astype(str).str.zfill(8)
    panel = pd.concat([dev_panel, hold_panel], ignore_index=True)
    panel = panel.drop_duplicates(["site_id", "DATE"], keep="last")
    return panel


def merge_air2stream(
    keys: pd.DataFrame,
    air2stream_path: Path,
    *,
    model: str = FR.AIR2STREAM_MODEL,
) -> pd.DataFrame:
    """Air2stream predictions re-scored on the common-key registry only."""
    if not air2stream_path.exists():
        raise FileNotFoundError(f"air2stream predictions missing: {air2stream_path}")
    a2s = pd.read_parquet(air2stream_path)
    a2s["site_id"] = a2s["site_id"].astype(str).str.zfill(8)
    a2s["issue_date"] = pd.to_datetime(a2s["issue_date"])
    merged = keys[["site_id", "horizon", "issue_date", "target_date", "y_true"]].merge(
        a2s[["site_id", "horizon", "issue_date", "y_pred"]],
        on=["site_id", "horizon", "issue_date"], how="inner",
        validate="one_to_one",
    )
    merged["model"] = model
    merged["seed"] = 0
    merged["calibration_state"] = "NOT_APPLICABLE_POINT_ONLY"
    return merged[["model", "seed", "site_id", "horizon", "issue_date",
                   "target_date", "y_true", "y_pred", "calibration_state"]]


def sha256_file(path: Path) -> str:
    digest = hashlib_sha256_file(path)
    return digest


def hashlib_sha256_file(path: Path) -> str:
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--predictions",
                        default=ROOT / "outputs" / "conventional" / "predictions_2021_2023.parquet")
    parser.add_argument("--air2stream",
                        default=ROOT / "outputs" / "conventional" / "air2stream_2021_2023.parquet")
    parser.add_argument("--registry", default=ROOT / "data_usgs" / "station_registry_v1.csv")
    parser.add_argument("--dev-panel", default=ROOT / "data_usgs" / "panel_usgs_120v2.parquet")
    parser.add_argument("--holdout-panel",
                        default=ROOT / "outputs" / "conventional" / "panel_2021_2023.parquet")
    parser.add_argument("--claim-ledger", default=ROOT / "paper" / "claim_ledger.yaml")
    parser.add_argument("--allow-incomplete-primary", action="store_true",
                        help="development only: proceed when plain-control arms are "
                             "missing from the prediction table (pre-scorer re-run)")
    parser.add_argument("--out", default=FINAL, type=Path)
    args = parser.parse_args(argv)

    started_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    args.out.mkdir(parents=True, exist_ok=True)

    predictions = pd.read_parquet(args.predictions)
    predictions["site_id"] = predictions["site_id"].astype(str).str.zfill(8)
    predictions["issue_date"] = pd.to_datetime(predictions["issue_date"])
    predictions["target_date"] = pd.to_datetime(predictions["target_date"])
    predictions["horizon"] = predictions["horizon"].astype(int)

    primary = predictions[predictions.model.isin(FR.PRIMARY_MODELS)].copy()
    missing = set(FR.PRIMARY_MODELS) - set(primary.model.unique())
    if missing and not args.allow_incomplete_primary:
        raise SystemExit(
            f"predictions table lacks primary models: {sorted(missing)}; "
            "the holdout scorer must be re-run with plain controls enabled")

    keys = FR.build_key_registry(primary)
    print(f"common forecast keys: {len(keys)} across "
          f"{keys.site_id.nunique()} stations")

    panel = load_combined_panel(args.dev_panel, args.holdout_panel)
    keys = FR.attach_context_missingness(keys, panel)
    keys.to_parquet(args.out / "forecast_keys.parquet", index=False)

    a2s = merge_air2stream(keys, args.air2stream)
    primary = pd.concat([primary, a2s], ignore_index=True)

    primary = primary[["model", "site_id", "horizon", "issue_date", "target_date",
                       "y_true", "y_pred", "q05", "q50", "q95", "p_exceed",
                       "calibration_state"]]
    primary.to_parquet(args.out / "predictions.parquet", index=False)

    station = FR.station_metrics(primary)
    FR.assert_common_station_sets(station)
    station.to_parquet(args.out / "station_metrics.parquet", index=False)

    pooled = FR.pooled_metrics(primary)
    pooled.to_parquet(args.out / "pooled_metrics.parquet", index=False)

    effects = FR.paired_effects(station)
    registry = load_registry(args.registry)
    effects = effects.merge(
        registry[["site_no", "huc2"]].rename(columns={"site_no": "site_id"}),
        on="site_id", how="left")
    effects.to_parquet(args.out / "paired_effects.parquet", index=False)

    decomp = FR.decomposition_effects(station)
    decomp.to_parquet(args.out / "decomposition_effects.parquet", index=False)

    # Consistency assertions (protocol v1: build fails on any breach).
    assert keys.duplicated("key_id").sum() == 0, "duplicate key ids"
    assert (keys["target_date"] == keys["issue_date"] + pd.to_timedelta(keys["horizon"], unit="D")).all(), \
        "target_date != issue_date + horizon"
    for (candidate, reference, horizon), g in effects.groupby(
            ["candidate", "reference", "horizon"]):
        assert g.n_common_keys.min() >= FR.MINIMUM_VALID_TARGETS, \
            f"paired cell below reportability: {candidate}/{reference}/h{horizon}"
    diff = (decomp["g_total"] - decomp["g_memory"] - decomp["g_learned"]).abs()
    assert diff.max() < 1e-12, "decomposition is not exactly additive"
    # skill is the median of per-station ratios; the ratio of medians is a
    # different quantity and must not be emitted as the macro.
    seven_damped = FR.median_station_skill(effects, "ThermoRoute", "DampedPersistence", 7)
    print(f"ThermoRoute 7d skill vs damped (median of station ratios): {seven_damped:.4f}")

    # Cluster inference for the SI block (frozen five-test family).
    registry_full = pd.read_csv(args.registry, dtype={"site_no": str})
    registry_full["site_no"] = registry_full["site_no"].str.strip()
    inference = CS.cluster_inference(
        effects.rename(columns={"delta_rmse": "effect"})[["candidate", "reference",
                                                          "horizon", "site_id", "effect"]],
        registry_full,
        holm_family_contrasts=CS.HOLM_FAMILY_CONTRASTS,
        n_boot=10000, seed=0)
    (args.out / "cluster_inference_2021_2023.json").write_text(
        json.dumps(inference, indent=1, default=str))

    # Claim ledger + paper values.
    import yaml
    with open(args.claim_ledger, encoding="utf-8") as fh:
        ledger = yaml.safe_load(fh)
    resolved = FR.resolve_claim_ledger(ledger, {
        path.name: pd.read_parquet(path)
        for path in args.out.glob("*.parquet")})
    unresolved = resolved[resolved.status != "RESOLVED"]
    resolved.to_csv(args.out / "claim_ledger_resolved.csv", index=False)
    FR.write_paper_values(resolved, args.out / "paper_values.tex")
    if not unresolved.empty:
        print(f"WARNING: {len(unresolved)} unresolved claims:")
        for row in unresolved.itertuples(index=False):
            print(f"  {row.claim_id}: {row.status}")

    git_sha = subprocess.run(
        ["git", "rev-parse", "HEAD"], capture_output=True, text=True,
        cwd=ROOT).stdout.strip()
    dirty = bool(subprocess.run(
        ["git", "status", "--porcelain"], capture_output=True, text=True,
        cwd=ROOT).stdout.strip())
    protocol_sha = sha256_file(ROOT / "protocols" / "wrr_strong_accept_protocol_v1.yaml")
    output_hashes = {
        path.name: sha256_file(path) for path in sorted(args.out.glob("*.parquet"))
    }
    completed_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    FR.write_manifest(
        args.out / "result_manifest.json",
        git_sha=git_sha, dirty=dirty,
        command=" ".join(sys.argv),
        protocol_sha256=protocol_sha,
        output_hashes=output_hashes,
        started_at=started_at, completed_at=completed_at)
    print(f"wrote results authority to {args.out}")
    print(f"git: {git_sha} (dirty={dirty})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
